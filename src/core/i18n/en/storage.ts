type StorageKind = 'bucket' | 'folder'

function inventory(files: number, folders: number, size: string) {
  const parts = [`${files} file${files === 1 ? '' : 's'}`, ...(folders ? [`${folders} folder${folders === 1 ? '' : 's'}`] : [])]
  return `${parts.join(' and ')} (${size})`
}

